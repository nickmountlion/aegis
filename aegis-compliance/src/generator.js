import { ISO27001_CONTROLS } from './controls-map.js';

/**
 * Generate standard Markdown report
 * @param {Object} scanResults - Results from aegis-scanner
 * @param {Object} gitInfo - Mock or real git metadata
 * @returns {string} Markdown document
 */
export function generateMarkdownReport(scanResults, gitInfo = {}) {
  const { meta, issues } = scanResults;
  let md = `# ISO/IEC 27001 Compliance Evidence Report\n\n`;
  md += `**Generated By**: AEGIS Compliance Module\n`;
  md += `**Timestamp**: ${new Date().toISOString()}\n`;
  md += `**Files Scanned**: ${meta.filesScanned}\n`;
  md += `**Scan Time**: ${meta.scanTimeMs}ms\n`;
  md += `**Total Security Findings**: ${meta.totalIssues} (Critical: ${meta.criticalCount}, High: ${meta.highCount}, Medium: ${meta.mediumCount}, Low: ${meta.lowCount})\n\n`;

  md += `## 1. Compliance Executive Summary\n\n`;
  md += `| Control | Name | Status | Score | Notes |\n`;
  md += `|---|---|---|---|---|\n`;

  for (const [controlId, control] of Object.entries(ISO27001_CONTROLS)) {
    const evaluation = control.evaluate(meta, issues, gitInfo);
    md += `| **${controlId}** | ${control.name} | \`${evaluation.status}\` | **${evaluation.score}%** | ${evaluation.notes} |\n`;
  }
  md += `\n`;

  md += `## 2. ISO 27001 Control Mapping Details\n\n`;

  for (const [controlId, control] of Object.entries(ISO27001_CONTROLS)) {
    const evaluation = control.evaluate(meta, issues, gitInfo);
    md += `### Control ${controlId}: ${control.name}\n`;
    md += `**Objective**: ${control.objective}\n\n`;
    md += `**Evidence Requirements**:\n`;
    control.evidenceRequirements.forEach(req => {
      md += `- [x] ${req}\n`;
    });
    md += `\n`;
    md += `**Audit Verdict**: **${evaluation.status}** (${evaluation.score}% Score)\n\n`;
    md += `*Auditor Notes*: ${evaluation.notes}\n\n`;
    md += `---\n\n`;
  }

  md += `## 3. Detailed Security Findings\n\n`;
  if (issues.length === 0) {
    md += `*No active security issues or vulnerabilities found in the codebase. Control checks verified.* \n`;
  } else {
    md += `| Severity | Rule ID | File | Line | Snippet | Description |\n`;
    md += `|---|---|---|---|---|---|\n`;
    issues.forEach(issue => {
      md += `| **${issue.severity}** | ${issue.ruleId} | \`${issue.file}\` | ${issue.line} | \`${issue.snippet}\` | ${issue.description} |\n`;
    });
  }
  
  return md;
}

